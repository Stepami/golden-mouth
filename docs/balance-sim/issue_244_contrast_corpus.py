def cases():
    counts = {}
    rows = []
    for category, family, world, previous, positive, negative in PAIRS:
        index = counts.get(category, 0)
        counts[category] = index + 1
        for label, text in ((True, positive), (False, negative)):
            rows.append(dict(id=f"{category}_{family}_{int(label)}", category=category,
                             family=family, split="dev" if index < 4 else "holdout",
                             world=world, previous=previous, expected=label, text=text))
    return rows
