export function starterFor(templateId:string|undefined, world:Pick<World,'title'|'topic'>):Starter {
  const prepared = templateId ? starters[templateId] : undefined;
  if(prepared)return {...prepared,xp:10};
  const context=world.topic.trim().replace(/\s+/g,' ').slice(0,700);
  return { title:'Начни свою историю', prompt:'Поделись отправной точкой истории и задай вопрос собеседникам.', xp:10,
    draft:`Начинаю историю в мире «${world.title}».${context ? ` Вот наша отправная точка: ${context}` : ''} Хочу разобраться в происходящем и услышать разные версии. С чего начнём?` };
}
