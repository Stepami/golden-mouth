/** Exact NPC selection only. Custom players and edited lore never inherit another character's story. */
export function characterGuidanceFor(player: { name: string; role: string }, world: WorldDefinition | WorldDocument): CharacterGuidance | undefined {
  const template = optionalWorldTemplate(world)
  if (!template || !world.description.includes(`\nПерсона игрока: ${player.name}. `)) return undefined
  return guidance.find(item => item.world === template.id && item.name === player.name && item.role === player.role)
}
